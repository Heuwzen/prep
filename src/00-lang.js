var DICT=UI_LANG==='tr'?TR:{};
/* t('Text {0}',a): the English text is the key; {0}, {1} take the extra arguments. Unknown keys stay English. */
function t(s){
  /* a key may end in |context to tell two meanings of one English word apart; English drops the context */
  var i=s.indexOf('|'),o=DICT.hasOwnProperty(s)?DICT[s]:(i<0?s:s.slice(0,i)),a=arguments;
  if(a.length>1)o=o.replace(/\{(\d+)\}/g,function(m,i){return a[+i+1]});
  return o;
}
